//uses browser's builtin print to pdf- no extra libraries
export function exportGraphAsPDF(graph, topic){
    if (!graph) return;

    const root = graph.root || {};
    const nodes = graph.nodes || [];

    //build html content
    const nodeHTML = [root, ...nodes].map(node => {
        const notes = node.notes || {};
        const questions = (node.questions || []).map((q, i) => `
        <div class="question">
            <div class="q-num">Q${i+1}</div> 
            <div class="q-text">${typeof q === 'string' ? q : q.q}</div>
            ${q.a ? `<div class="q-answer"><strong>Answer:</strong> ${q.a}</div>` : ''}
            ${q.explanation ? `<div class="q-explain"><strong>Explanation:</strong> ${q.explanation}</div>` : ''}
        </div>
        `).join('');

        const concepts = (notes.keyConcepts || []).map(c => `<li>${c}</li>`).join('');
        const points = (notes.keyPoints || []).map(p => `<li>${p}</li>`).join('');

        return `
        <div class="node">
        <h2>${node.label || ''}</h2>
        ${notes.overview ? `<div class="section"><h3>Overview</h3><p>${notes.overview}</p></div>` : ''}
        ${concepts ? `<div class="section"><h3>Key Concepts</h3><ul>${concepts}</ul></div>` : ''}
        ${notes.example ? `<div class="section"><h3>Example</h3><p>${notes.example}</p></div>` : ''}
        ${points ? `<div class="section"><h3>Key Takeaways</h3><ul>${points}</ul></div>` : ''}
        ${questions ? `<div class="section"><h3>Practice Questions</h3>${questions}</div>` : ''}
        </div>
        `;
    }).join('');

    const html = `
        <!DOCTYPE html>
    <html>
    <head>
      <meta charset="utf-8" />
      <title>${topic} — Synapse.ai Notes</title>
      <style>
        * { box-sizing: border-box; margin: 0; padding: 0; }
        body {
          font-family: 'Segoe UI', Arial, sans-serif;
          font-size: 13px;
          color: #1a1a1a;
          background: #fff;
          padding: 40px;
          line-height: 1.6;
        }
        .header {
          border-bottom: 2px solid #1a1a1a;
          padding-bottom: 16px;
          margin-bottom: 32px;
        }
        .header h1 { font-size: 24px; font-weight: 700; }
        .header .meta { font-size: 11px; color: #666; margin-top: 4px; }
        .node {
          margin-bottom: 36px;
          page-break-inside: avoid;
        }
        .node h2 {
          font-size: 17px;
          font-weight: 600;
          border-left: 3px solid #1a1a1a;
          padding-left: 10px;
          margin-bottom: 14px;
        }
        .section { margin-bottom: 14px; }
        .section h3 {
          font-size: 10px;
          letter-spacing: 0.1em;
          text-transform: uppercase;
          color: #666;
          margin-bottom: 6px;
        }
        .section p { color: #333; }
        .section ul { padding-left: 18px; color: #333; }
        .section li { margin-bottom: 4px; }
        .question {
          background: #f8f8f8;
          border: 1px solid #e0e0e0;
          border-radius: 6px;
          padding: 12px;
          margin-bottom: 10px;
        }
        .q-num { font-size: 10px; color: #999; margin-bottom: 4px; }
        .q-text { font-weight: 500; margin-bottom: 8px; }
        .q-answer { color: #333; margin-bottom: 4px; }
        .q-explain { color: #555; font-style: italic; }
        .footer {
          margin-top: 40px;
          padding-top: 12px;
          border-top: 1px solid #ddd;
          font-size: 10px;
          color: #aaa;
          text-align: center;
        }
        @media print {
          body { padding: 20px; }
          .node { page-break-inside: avoid; }
        }
      </style>
    </head>
    <body>
      <div class="header">
        <h1>${topic}</h1>
        <div class="meta">Generated by Synapse.ai — ${new Date().toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' })}</div>
      </div>
      ${nodeHTML}
      <div class="footer">synapse-ai.onrender.com</div>
    </body>
    </html>
    `;

    //create a temp URL from the HTML content and open it in new tab
    const blob = new Blob([html], {type: 'text/html'});
    const url = URL.createObjectURL(blob);
    const win = window.open(url, '_blank');
    win.onLoad = () => {
        win.print();
        URL.revokeObjectURL(url); // clean up memory after the print
    };

}